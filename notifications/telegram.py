def build_translator(lang):
    active_lang = resolve_operational_notification_locale(lang)
    def translate(key, **kwargs):
        template = I18N[active_lang].get(key, key)
        return template.format(**kwargs) if kwargs else template

    return translate


def build_strategy_display_name(translate_fn, locale: str = "en"):
    def strategy_display_name(
        profile: str,
        *,
        fallback_name: str | None = None,
        metadata=None,
    ) -> str:
        if metadata is not None:
            from quant_platform_kit.common.notification_localization import (
                resolve_strategy_display_name,
            )
            return resolve_strategy_display_name(
                locale, metadata, translator=translate_fn,
            )

        key = f"strategy_name_{str(profile or '').strip()}"
        translated = translate_fn(key)
        if translated != key:
            return translated
        fallback = str(fallback_name or "").strip()
        if fallback:
            return fallback
        return str(profile or "").strip()

    return strategy_display_name


def _safe_telegram_error_text(value, *, token=None, max_chars=300):
    text = str(value or "")
    if token:
        text = text.replace(str(token), "<redacted>")
    if len(text) > max_chars:
        text = f"{text[:max_chars]}..."
    return text


def send_telegram_message(
    message,
    *,
    token,
    chat_id,
    requests_module,
    printer=print,
):
    if not token or not chat_id:
        return False

    url = f"https://api.telegram.org/bot{token}/sendMessage"
    try:
        printer(f"TG:\n{message}", flush=True)
        response = requests_module.post(
            url,
            json={"chat_id": chat_id, "text": _break_telegram_market_symbol_auto_links(message)},
            timeout=10,
        )
        if not 200 <= response.status_code < 300:
            printer(
                "Telegram send failed with status "
                f"{response.status_code}: {_safe_telegram_error_text(response.text, token=token)}",
                flush=True,
            )
            return False
        load_payload = getattr(response, "json", None)
        payload = load_payload() if callable(load_payload) else None
        if isinstance(payload, dict) and payload.get("ok") is False:
            printer("Telegram send failed: negative API acknowledgement", flush=True)
            return False
    except Exception as exc:
        printer(f"Telegram send failed: {type(exc).__name__}", flush=True)
        return False
    return True
